import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { join } from "node:path";

import { loadEnv } from "vite";

const dir = process.env.DIST_DIR || "dist";
const env = loadEnv("production", process.cwd(), "VITE_");
const site = env.VITE_SITE_URL?.trim().replace(/\/+$/, "");
assert(site, "Set the same VITE_SITE_URL used for the build");
const html = await readFile(join(dir, "index.html"), "utf8");
const robots = await readFile(join(dir, "robots.txt"), "utf8");
const sitemap = await readFile(join(dir, "sitemap.xml"), "utf8");
const image = await readFile(join(dir, "og.png"));
assert.match(html, /<html lang="ar" dir="rtl">/);
assert(html.includes("EduFormation — منصتك التدريبية بهويتك | H2D.dev"));
assert(html.includes(`rel="canonical" href="${site}/"`));
assert(html.includes(`property="og:url" content="${site}/"`));
assert(html.includes(`property="og:image" content="${site}/og.png"`));
assert(html.includes('property="og:locale" content="ar_AR"'));
assert(html.includes('property="og:locale:alternate" content="en_US"'));
assert(html.includes('property="og:locale:alternate" content="fr_FR"'));
assert(html.includes('name="twitter:card" content="summary_large_image"'));
const description = html.match(/<meta name="description" content="([^"]*)"/);
assert(description && description[1].length <= 155);
assert.match(html, /rel="preload" href="\/assets\/InterVariable-[^"]+\.woff2" as="font"/);
assert(!/open the platform|openPlatform/i.test(html));
assert.match(robots, /User-agent: \*\s+Allow: \//);
assert(robots.includes(`Sitemap: ${site}/sitemap.xml`));
assert.equal((sitemap.match(/<loc>/g) || []).length, 1);
assert(sitemap.includes(`<loc>${site}/</loc>`));
const jsonText = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
assert(jsonText, "JSON-LD is missing");
const data = JSON.parse(jsonText[1]);
assert.equal(data["@context"], "https://schema.org");
assert.deepEqual(data["@graph"].map((item) => item["@type"]), ["Organization", "SoftwareApplication"]);
assert.equal(data["@graph"][0].name, "H2D.dev");
assert(data["@graph"][1].description.includes("مخصصة لكل أكاديمية أو شركة"));
assert(!/"(?:aggregateRating|review|offers)"/.test(jsonText[1]));
assert.equal(image.readUInt32BE(16), 1200);
assert.equal(image.readUInt32BE(20), 630);
console.log("Metadata, structured data, static routes, sitemap, robots and OG dimensions pass.");
